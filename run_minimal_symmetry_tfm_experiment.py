#!/usr/bin/env python3

from __future__ import annotations

import argparse
import csv
import json
import time
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


MODELS = ("tabpfn", "tabicl", "gbdt")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run TabPFN, TabICL, or a GBDT baseline on a minimal binary-relation table."
    )
    parser.add_argument(
        "--data-path",
        type=Path,
        default=Path("minimal_symmetry_dataset") / "symmetry_friendship_atoms.csv",
        help="CSV generated by generate_minimal_symmetry_dataset.py.",
    )
    parser.add_argument("--output-dir", type=Path, default=Path("minimal_symmetry_results"))
    parser.add_argument("--models", type=str, default="tabpfn,tabicl")
    parser.add_argument("--device", type=str, default="cpu")
    parser.add_argument("--seed", type=int, default=20260429)
    parser.add_argument("--decision-threshold", type=float, default=0.5)
    parser.add_argument(
        "--threshold-mode",
        type=str,
        default="fixed",
        choices=["fixed", "tune_validation_f1"],
    )
    parser.add_argument("--tabpfn-model-path", type=Path, default=None)
    parser.add_argument("--tabpfn-n-estimators", type=int, default=4)
    parser.add_argument(
        "--tabpfn-fit-mode",
        type=str,
        default="fit_preprocessors",
        choices=["low_memory", "fit_preprocessors", "fit_with_cache", "batched"],
    )
    parser.add_argument("--tabpfn-memory-saving-mode", type=str, default="auto")
    parser.add_argument("--tabpfn-inference-precision", type=str, default="auto")
    parser.add_argument("--tabicl-model-path", type=Path, default=None)
    parser.add_argument("--tabicl-n-estimators", type=int, default=4)
    parser.add_argument("--tabicl-batch-size", type=int, default=8)
    parser.add_argument("--tabicl-use-amp", type=str, default="auto")
    parser.add_argument("--tabicl-use-fa3", type=str, default="auto")
    parser.add_argument("--tabicl-offload-mode", type=str, default="auto")
    parser.add_argument("--gbdt-n-estimators", type=int, default=200)
    parser.add_argument("--gbdt-learning-rate", type=float, default=0.05)
    parser.add_argument("--gbdt-max-depth", type=int, default=3)
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Validate the dataset and print the run plan without importing model packages.",
    )
    return parser.parse_args()


def parse_csv_list(text: str) -> list[str]:
    return [part.strip() for part in text.split(",") if part.strip()]


def parse_bool_or_auto(text: str) -> bool | str:
    lowered = text.strip().lower()
    if lowered == "auto":
        return "auto"
    if lowered in {"true", "1", "yes", "y"}:
        return True
    if lowered in {"false", "0", "no", "n"}:
        return False
    raise ValueError(f"Expected auto/true/false, got {text!r}.")


def validate_args(args: argparse.Namespace) -> list[str]:
    selected_models = parse_csv_list(args.models)
    unknown_models = sorted(set(selected_models) - set(MODELS))
    if unknown_models:
        raise ValueError(f"Unknown model(s): {unknown_models}. Valid options are {list(MODELS)}.")
    if not selected_models:
        raise ValueError("No models selected.")
    if not args.data_path.exists():
        raise FileNotFoundError(f"Dataset not found: {args.data_path}")
    if not 0.0 <= args.decision_threshold <= 1.0:
        raise ValueError("--decision-threshold must be in [0, 1].")

    if not args.dry_run:
        if "tabpfn" in selected_models:
            if args.tabpfn_model_path is None:
                raise ValueError("--tabpfn-model-path is required when running TabPFN.")
            if not args.tabpfn_model_path.exists():
                raise FileNotFoundError(f"TabPFN checkpoint not found: {args.tabpfn_model_path}")
        if "tabicl" in selected_models:
            if args.tabicl_model_path is None:
                raise ValueError("--tabicl-model-path is required when running TabICL.")
            if not args.tabicl_model_path.exists():
                raise FileNotFoundError(f"TabICL checkpoint not found: {args.tabicl_model_path}")
    return selected_models


def import_runtime_dependencies() -> None:
    global np
    global pd
    global accuracy_score
    global average_precision_score
    global f1_score
    global precision_score
    global recall_score
    global roc_auc_score
    global GradientBoostingClassifier

    try:
        import numpy as np_module
        import pandas as pd_module
        from sklearn.ensemble import GradientBoostingClassifier as GradientBoostingClassifier_cls
        from sklearn.metrics import accuracy_score as accuracy_score_fn
        from sklearn.metrics import average_precision_score as average_precision_score_fn
        from sklearn.metrics import f1_score as f1_score_fn
        from sklearn.metrics import precision_score as precision_score_fn
        from sklearn.metrics import recall_score as recall_score_fn
        from sklearn.metrics import roc_auc_score as roc_auc_score_fn
    except ModuleNotFoundError as exc:
        raise SystemExit(
            f"Missing Python dependency: {exc.name}. Run this script inside the TFM environment "
            "with numpy, pandas, scikit-learn, the selected model packages, and any required checkpoints installed."
        ) from exc

    np = np_module
    pd = pd_module
    GradientBoostingClassifier = GradientBoostingClassifier_cls
    accuracy_score = accuracy_score_fn
    average_precision_score = average_precision_score_fn
    f1_score = f1_score_fn
    precision_score = precision_score_fn
    recall_score = recall_score_fn
    roc_auc_score = roc_auc_score_fn


def load_dataset_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        rows = list(reader)

    if not rows:
        raise ValueError("Dataset is empty.")

    required = {"entity_1", "entity_2", "label", "split"}
    actual_columns = set(rows[0])
    missing = sorted(required - actual_columns)
    if missing:
        raise ValueError(f"Dataset is missing required columns: {missing}")
    forbidden = sorted({"hidden_group_id", "source_group_id", "target_group_id", "group_id"} & actual_columns)
    if forbidden:
        raise ValueError(f"Model-facing dataset contains hidden group columns: {forbidden}")

    splits = {str(row["split"]) for row in rows}
    if splits - {"train", "validation", "test"}:
        raise ValueError("split must contain only train, validation, and test.")
    try:
        labels = [int(row["label"]) for row in rows]
    except ValueError as exc:
        raise ValueError("label must be binary 0/1.") from exc
    if set(labels) - {0, 1}:
        raise ValueError("label must be binary 0/1.")

    train_labels = [int(row["label"]) for row in rows if row["split"] == "train"]
    test_labels = [int(row["label"]) for row in rows if row["split"] == "test"]
    if not train_labels or not test_labels:
        raise ValueError("Dataset must contain non-empty train and test splits.")
    if len(set(train_labels)) < 2:
        raise ValueError("Train split must contain both classes.")
    if len(set(test_labels)) < 2:
        raise ValueError("Test split must contain both classes.")
    return rows


def make_feature_frame(df: Any, entity_categories: list[str]) -> Any:
    entity_dtype = pd.CategoricalDtype(categories=entity_categories, ordered=False)
    return pd.DataFrame(
        {
            "entity_1": pd.Series(df["entity_1"].astype(str), dtype=entity_dtype),
            "entity_2": pd.Series(df["entity_2"].astype(str), dtype=entity_dtype),
        }
    )


def encode_for_tabpfn(X: Any) -> Any:
    return np.column_stack(
        [
            X["entity_1"].cat.codes.to_numpy(dtype=np.int64),
            X["entity_2"].cat.codes.to_numpy(dtype=np.int64),
        ]
    )


def build_tabpfn_classifier(args: argparse.Namespace):
    from tabpfn import TabPFNClassifier

    return TabPFNClassifier(
        model_path=str(args.tabpfn_model_path),
        device=args.device,
        n_estimators=args.tabpfn_n_estimators,
        categorical_features_indices=[0, 1],
        ignore_pretraining_limits=True,
        fit_mode=args.tabpfn_fit_mode,
        memory_saving_mode=args.tabpfn_memory_saving_mode,
        inference_precision=args.tabpfn_inference_precision,
        n_preprocessing_jobs=1,
        random_state=args.seed,
    )


def build_tabicl_classifier(args: argparse.Namespace):
    from tabicl import TabICLClassifier

    return TabICLClassifier(
        model_path=str(args.tabicl_model_path),
        allow_auto_download=False,
        device=args.device,
        n_estimators=args.tabicl_n_estimators,
        batch_size=args.tabicl_batch_size,
        use_amp=parse_bool_or_auto(args.tabicl_use_amp),
        use_fa3=parse_bool_or_auto(args.tabicl_use_fa3),
        offload_mode=args.tabicl_offload_mode,
        random_state=args.seed,
        verbose=False,
    )


def build_gbdt_classifier(args: argparse.Namespace):
    if args.gbdt_n_estimators <= 0:
        raise ValueError("--gbdt-n-estimators must be positive.")
    if args.gbdt_learning_rate <= 0.0:
        raise ValueError("--gbdt-learning-rate must be positive.")
    if args.gbdt_max_depth <= 0:
        raise ValueError("--gbdt-max-depth must be positive.")
    return GradientBoostingClassifier(
        n_estimators=args.gbdt_n_estimators,
        learning_rate=args.gbdt_learning_rate,
        max_depth=args.gbdt_max_depth,
        random_state=args.seed,
    )


def extract_positive_proba(proba: np.ndarray, classes: np.ndarray) -> np.ndarray:
    classes = np.asarray(classes)
    proba = np.asarray(proba)
    if proba.ndim != 2 or proba.shape[1] != len(classes):
        raise ValueError("Unexpected predict_proba output shape.")
    positive_matches = np.where(classes == 1)[0]
    if positive_matches.size != 1:
        raise ValueError(f"Could not identify positive class in classes={classes!r}.")
    return proba[:, int(positive_matches[0])].astype(np.float64)


def predict_positive_proba(model: Any, X_query: Any) -> np.ndarray:
    return extract_positive_proba(np.asarray(model.predict_proba(X_query)), np.asarray(model.classes_))


def best_f1_threshold(y_true: np.ndarray, positive_proba: np.ndarray, default_threshold: float) -> float:
    if len(y_true) == 0 or np.unique(y_true).size < 2:
        return float(default_threshold)
    candidates = np.unique(np.concatenate([np.linspace(0.0, 1.0, 101), positive_proba, [default_threshold]]))
    best_threshold = float(default_threshold)
    best_score = -1.0
    for threshold in candidates:
        score = float(f1_score(y_true, (positive_proba >= threshold).astype(np.int64), zero_division=0))
        if score > best_score:
            best_score = score
            best_threshold = float(threshold)
    return best_threshold


def evaluate_predictions(y_true: np.ndarray, y_pred: np.ndarray, positive_proba: np.ndarray) -> dict[str, float]:
    metrics = {
        "accuracy": float(accuracy_score(y_true, y_pred)),
        "f1": float(f1_score(y_true, y_pred, zero_division=0)),
        "precision": float(precision_score(y_true, y_pred, zero_division=0)),
        "recall": float(recall_score(y_true, y_pred, zero_division=0)),
        "positive_rate_true": float(np.mean(y_true)),
        "positive_rate_pred": float(np.mean(y_pred)),
    }
    if np.unique(y_true).size < 2:
        metrics["average_precision"] = float("nan")
        metrics["roc_auc"] = float("nan")
    else:
        metrics["average_precision"] = float(average_precision_score(y_true, positive_proba))
        metrics["roc_auc"] = float(roc_auc_score(y_true, positive_proba))
    return metrics


def fit_predict_one_model(
    *,
    model_name: str,
    X_train: Any,
    y_train: np.ndarray,
    X_valid: Any,
    y_valid: np.ndarray,
    X_test: Any,
    args: argparse.Namespace,
) -> dict[str, object]:
    if model_name == "tabpfn":
        model = build_tabpfn_classifier(args)
        X_train_in = encode_for_tabpfn(X_train)
        X_valid_in = encode_for_tabpfn(X_valid) if len(X_valid) else np.empty((0, 2), dtype=np.int64)
        X_test_in = encode_for_tabpfn(X_test)
    elif model_name == "tabicl":
        model = build_tabicl_classifier(args)
        X_train_in = X_train
        X_valid_in = X_valid
        X_test_in = X_test
    elif model_name == "gbdt":
        model = build_gbdt_classifier(args)
        X_train_in = encode_for_tabpfn(X_train)
        X_valid_in = encode_for_tabpfn(X_valid) if len(X_valid) else np.empty((0, 2), dtype=np.int64)
        X_test_in = encode_for_tabpfn(X_test)
    else:
        raise ValueError(f"Unsupported model: {model_name}")

    fit_start = time.perf_counter()
    model.fit(X_train_in, y_train)
    fit_time_s = time.perf_counter() - fit_start

    pred_start = time.perf_counter()
    valid_proba = predict_positive_proba(model, X_valid_in) if len(X_valid) else np.asarray([], dtype=np.float64)
    test_proba = predict_positive_proba(model, X_test_in)
    predict_time_s = time.perf_counter() - pred_start

    threshold = (
        best_f1_threshold(y_valid, valid_proba, args.decision_threshold)
        if args.threshold_mode == "tune_validation_f1"
        else float(args.decision_threshold)
    )
    y_pred = (test_proba >= threshold).astype(np.int64)
    return {
        "positive_proba": test_proba,
        "y_pred": y_pred,
        "threshold": float(threshold),
        "fit_time_s": float(fit_time_s),
        "predict_time_s": float(predict_time_s),
    }


def write_json(path: Path, payload: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True), encoding="utf-8")


def build_findings(metrics_df: Any, args: argparse.Namespace) -> str:
    lines = [
        "# Minimal Symmetry TFM Findings",
        "",
        f"- data path: `{args.data_path}`",
        f"- threshold mode: `{args.threshold_mode}`",
        f"- device: `{args.device}`",
        "",
        "| Model | Accuracy | F1 | Average Precision | ROC AUC | Threshold |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for _, row in metrics_df.sort_values("model").iterrows():
        lines.append(
            "| {model} | {accuracy:.4f} | {f1:.4f} | {average_precision:.4f} | {roc_auc:.4f} | {threshold:.4f} |".format(
                **row.to_dict()
            )
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    args = parse_args()
    selected_models = validate_args(args)
    rows = load_dataset_rows(args.data_path)
    entity_categories = sorted({row["entity_1"] for row in rows} | {row["entity_2"] for row in rows})

    train_rows = [row for row in rows if row["split"] == "train"]
    valid_rows = [row for row in rows if row["split"] == "validation"]
    test_rows = [row for row in rows if row["split"] == "test"]

    if args.dry_run:
        print(f"data_path: {args.data_path.resolve()}")
        print(f"models: {selected_models}")
        print(f"entities: {len(entity_categories)}")
        print(f"train_rows: {len(train_rows)}")
        print(f"validation_rows: {len(valid_rows)}")
        print(f"test_rows: {len(test_rows)}")
        print("train_label_counts:")
        for label, count in sorted(Counter(int(row["label"]) for row in train_rows).items()):
            print(f"{label}    {count}")
        print("test_label_counts:")
        for label, count in sorted(Counter(int(row["label"]) for row in test_rows).items()):
            print(f"{label}    {count}")
        return

    import_runtime_dependencies()

    df = pd.DataFrame(rows)
    df["label"] = df["label"].astype(int)
    train_df = df.loc[df["split"] == "train"].reset_index(drop=True)
    valid_df = df.loc[df["split"] == "validation"].reset_index(drop=True)
    test_df = df.loc[df["split"] == "test"].reset_index(drop=True)

    X_train = make_feature_frame(train_df, entity_categories)
    X_valid = make_feature_frame(valid_df, entity_categories)
    X_test = make_feature_frame(test_df, entity_categories)
    y_train = train_df["label"].astype(int).to_numpy()
    y_valid = valid_df["label"].astype(int).to_numpy()
    y_test = test_df["label"].astype(int).to_numpy()

    args.output_dir.mkdir(parents=True, exist_ok=True)
    metric_rows: list[dict[str, object]] = []
    prediction_rows: list[pd.DataFrame] = []

    for model_name in selected_models:
        result = fit_predict_one_model(
            model_name=model_name,
            X_train=X_train,
            y_train=y_train,
            X_valid=X_valid,
            y_valid=y_valid,
            X_test=X_test,
            args=args,
        )
        metrics = evaluate_predictions(y_test, result["y_pred"], result["positive_proba"])
        metric_rows.append(
            {
                "model": model_name,
                "threshold": result["threshold"],
                "fit_time_s": result["fit_time_s"],
                "predict_time_s": result["predict_time_s"],
                **metrics,
            }
        )
        prediction_columns = [col for col in ["atom_id", "pair_id", "entity_1", "entity_2", "label"] if col in test_df.columns]
        model_predictions = test_df[prediction_columns].copy()
        model_predictions["model"] = model_name
        model_predictions["positive_proba"] = result["positive_proba"]
        model_predictions["prediction"] = result["y_pred"]
        prediction_rows.append(model_predictions)

    metrics_df = pd.DataFrame(metric_rows)
    predictions_df = pd.concat(prediction_rows, axis=0, ignore_index=True)
    metrics_df.to_csv(args.output_dir / "metrics.csv", index=False)
    predictions_df.to_csv(args.output_dir / "predictions.csv", index=False)
    write_json(
        args.output_dir / "metadata.json",
        {
            "created_utc": datetime.now(timezone.utc).isoformat(),
            "data_path": str(args.data_path.resolve()),
            "models": selected_models,
            "device": args.device,
            "threshold_mode": args.threshold_mode,
            "train_rows": int(len(train_df)),
            "validation_rows": int(len(valid_df)),
            "test_rows": int(len(test_df)),
        },
    )
    (args.output_dir / "findings.md").write_text(build_findings(metrics_df, args), encoding="utf-8")
    print(metrics_df.to_string(index=False))


if __name__ == "__main__":
    main()
